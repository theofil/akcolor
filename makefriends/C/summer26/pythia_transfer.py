#!/usr/bin/env python3
"""
Generator-transfer tables for the Z_only_table/W_only_table nets: at each
net's already-tabulated Herwig S/sqrt(B)-optimal (eff_sig, eff_bkg) operating
point (sb_estimate.analyze_one), recover the exact NN-score threshold that
produced it, then apply that SAME score cut to the full MG5+Pythia sample
(never seen in training) -- a true transfer test of whether the working
point chosen on Herwig still holds up when the same events are generated by
a different generator. No re-optimization on Pythia and no retraining: the
network and its cut are exactly as chosen from Herwig alone.

roc_data_{channel}.npz only stores a decimated (fpr, tpr) curve -- the
underlying threshold values are discarded and never saved -- so the cut must
be recovered by re-scoring the Herwig test split at full resolution and
matching sb_estimate's tabulated (eff_sig, eff_bkg) point. Same technique as
spva_signal_region.py's channel_histograms(), generalized here to every
Z_only_table/W_only_table net (Kj/KjB/KjjBj feedforward nets included, whose
inference.py modules use a differently-named model class and a single-
scaler run_nn signature -- handled generically via model-class introspection
instead of a hardcoded class name).

The Z-only performance & resilience table is built the same way, except that
its Herwig operating point is the ROC-grid point maximizing performance =
eff_sig/sqrt(eff_bkg) itself (herwig_performance_optimum: same grid, same
raw-B floor, only the objective differs). For a fixed sample
S/sqrt(B) = [S_tot*sqrt(L)/sqrt(B_tot)] * eff_sig/sqrt(eff_bkg), so both
objectives must pick the same grid point; main() checks this explicitly
(print_operating_point_check). Both the Herwig and the Pythia efficiencies in
that table come from the one identical score cut (score >= cut), applied to
the re-scored Herwig test split and to the re-scored full MG5+Pythia sample.

Writes figs/summer26/pythia_transfer.txt and figs/summer26/
Z_performance_resilience.txt, and prints ready-to-paste markdown tables.
Runs on a GPU node: condor_submit -name bigbird24.cern.ch
summer26/pythia_transfer_gpu.sub (log in summer26/logs/).
"""
import functools
import importlib
import pathlib
import pickle
import sys

import numpy as np
import h5py
import torch
import torch.nn as nn
from sklearn.metrics import roc_curve

HERE = pathlib.Path(__file__).parent
sys.path.insert(0, str(HERE))
import sb_estimate as sbe

FIGS_DIR = sbe.FIGS_DIR
OUT_TXT  = FIGS_DIR / 'pythia_transfer.txt'
OUT_TXT_PERF = FIGS_DIR / 'Z_performance_resilience.txt'

PERF_MIN_RAW_BKG    = 20    # raised statistical floor (Z-only performance/resilience table)
PERFORMANCE_BASELINE = 1.00  # eff_sig=eff_bkg=1 at the no-tagging point -- generator-independent by construction

MG5_FILES = {
    'H': dict(bkg='QCDHjj_mg5_pythia.h5', sig='VBFH_mg5_pythia.h5'),
    'W': dict(bkg='QCDWjj_mg5_pythia.h5', sig='VBFW_mg5_pythia.h5'),
    'Z': dict(bkg='QCDZjj_mg5_pythia.h5', sig='VBFZ_mg5_pythia.h5'),
}


def _model_class(model_module):
    """The single nn.Module subclass defined directly in this net's own
    model.py (name differs per net family: JetNN, KjNN, KjBNN, KjjBjNN...)."""
    for obj in vars(model_module).values():
        if isinstance(obj, type) and issubclass(obj, nn.Module) and obj.__module__ == model_module.__name__:
            return obj
    raise RuntimeError(f'no nn.Module subclass found in {model_module}')


@functools.lru_cache(maxsize=None)
def get_scores(net, channel):
    """Re-score net's own Herwig test split and the full MG5+Pythia sample
    with its saved model, reusing that net's own dataset.py/model.py/
    inference.py verbatim (load_features/run_nn/BKG_FILE_MG5/SIG_FILE_MG5),
    generalized across every net family via model-class introspection.
    Cached: a Z net is transferred twice (S/sqrt(B)- and performance-chosen
    points) from one single scoring pass."""
    ndir = sbe.net_dir(net, channel)
    for m in ('dataset', 'model', 'inference'):
        sys.modules.pop(m, None)
    sys.path.insert(0, str(ndir))
    inf       = importlib.import_module('inference')
    model_mod = importlib.import_module('model')

    feats_bkg_hw = inf.load_features(inf.HERE / inf.BKG_FILE)
    feats_sig_hw = inf.load_features(inf.HERE / inf.SIG_FILE)
    feats_all_hw = [np.concatenate([b, s], axis=0) for b, s in zip(feats_bkg_hw[:-1], feats_sig_hw[:-1])]
    y_all_hw = np.concatenate([np.zeros(len(feats_bkg_hw[0]), dtype=np.float32),
                                np.ones(len(feats_sig_hw[0]), dtype=np.float32)])
    idx_test = np.load(inf.HERE / f'split_indices_{channel}.npz')['test_idx']
    feats_test = [f[idx_test] for f in feats_all_hw]
    y_test = y_all_hw[idx_test]

    feats_bkg_mg5 = inf.load_features(inf.HERE / inf.BKG_FILE_MG5)
    feats_sig_mg5 = inf.load_features(inf.HERE / inf.SIG_FILE_MG5)
    feats_all_mg5 = [np.concatenate([b, s], axis=0) for b, s in zip(feats_bkg_mg5[:-1], feats_sig_mg5[:-1])]
    y_mg5 = np.concatenate([np.zeros(len(feats_bkg_mg5[0]), dtype=np.float32),
                             np.ones(len(feats_sig_mg5[0]), dtype=np.float32)])

    with open(inf.HERE / f'scaler_{channel}.pkl', 'rb') as fh:
        scalers = pickle.load(fh)
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    model = _model_class(model_mod)().to(device)
    model.load_state_dict(torch.load(inf.HERE / f'best_model_{channel}.pt', map_location=device))
    model.eval()

    scores_test = inf.run_nn(model, scalers, *feats_test, device)
    scores_mg5  = inf.run_nn(model, scalers, *feats_all_mg5, device)
    return scores_test, y_test, scores_mg5, y_mg5


def herwig_performance_optimum(net, channel, min_raw_bkg=PERF_MIN_RAW_BKG):
    """Herwig operating point maximizing performance = eff_sig/sqrt(eff_bkg),
    scanned over exactly the grid sb_estimate.analyze_one scans for S/sqrt(B)
    (the net's own decimated Herwig test-split ROC in roc_data_{channel}.npz),
    with the same raw-B >= min_raw_bkg floor -- only the objective differs.
    eff_bkg = 0 points are excluded, as significance_curve() excludes B = 0.
    Returns the keys analyze_one_transfer() reads from sb_estimate.analyze_one."""
    ndir = sbe.net_dir(net, channel)
    roc = np.load(ndir / f'roc_data_{channel}.npz')
    fpr, tpr = roc['fpr_hw'], roc['tpr_hw']
    _, n_bkg_full = sbe.kweight_sum_and_n(sbe.FRIENDS_DIR / sbe.CHANNEL_FILES[channel]['bkg'])
    n_bkg_pop, n_sig_pop = sbe.herwig_test_split_counts(ndir, channel, n_bkg_full)
    perf = np.where(fpr > 0, tpr / np.sqrt(np.maximum(fpr, 1e-300)), -1.0)
    i_star, floor_bound = sbe.find_optimum(perf, fpr * n_bkg_pop, min_raw_bkg=min_raw_bkg)
    return dict(eff_sig=float(tpr[i_star]), eff_bkg=float(fpr[i_star]),
                floor_bound=floor_bound, raw_S0=n_sig_pop, raw_B0=n_bkg_pop)


def analyze_one_transfer(net, channel, min_raw_bkg=sbe.MIN_RAW_BKG, objective='significance'):
    """Herwig-chosen operating point -- the Herwig ROC-grid point maximizing
    S/sqrt(B) (objective='significance', sb_estimate.analyze_one) or
    performance = eff_sig/sqrt(eff_bkg) (objective='performance',
    herwig_performance_optimum), subject to a raw-B >= min_raw_bkg
    statistical-validity floor -- transferred as-is (same NN-score cut, no
    re-optimization) onto the full MG5+Pythia sample. eff_sig_hw/eff_bkg_hw
    are re-evaluated with that same cut on the re-scored Herwig test split, so
    the Herwig and Pythia efficiencies come from one identical cut; the chosen
    grid point itself is kept as eff_sig_hw_grid/eff_bkg_hw_grid."""
    if objective == 'significance':
        r_hw = sbe.analyze_one(net, channel, min_raw_bkg=min_raw_bkg)
    elif objective == 'performance':
        r_hw = herwig_performance_optimum(net, channel, min_raw_bkg=min_raw_bkg)
    else:
        raise ValueError(f'unknown objective {objective!r}')

    scores_test, y_test, scores_mg5, y_mg5 = get_scores(net, channel)
    fpr, tpr, thr = roc_curve(y_test, scores_test)
    dist2 = (fpr - r_hw['eff_bkg']) ** 2 + (tpr - r_hw['eff_sig']) ** 2
    i_star = int(np.argmin(dist2))
    cut = float(thr[i_star])

    def counts_at_cut(scores, y):
        passing = scores >= cut          # same convention as sklearn's roc_curve
        return (int((passing & (y == 1)).sum()), int((passing & (y == 0)).sum()),
                int((y == 1).sum()), int((y == 0).sum()))

    raw_S_hw, raw_B_hw, n_sig_hw, n_bkg_hw = counts_at_cut(scores_test, y_test)
    n_sig, n_bkg, n_sig_py, n_bkg_py = counts_at_cut(scores_mg5, y_mg5)
    eff_sig_hw = raw_S_hw / n_sig_hw
    eff_bkg_hw = raw_B_hw / n_bkg_hw
    eff_sig = n_sig / n_sig_py
    eff_bkg = n_bkg / n_bkg_py
    if (n_sig_hw, n_bkg_hw) != (r_hw['raw_S0'], r_hw['raw_B0']):
        print(f'WARNING {net} {channel}: Herwig test-split population from scoring '
              f'(sig={n_sig_hw}, bkg={n_bkg_hw}) != sb_estimate '
              f'(sig={r_hw["raw_S0"]}, bkg={r_hw["raw_B0"]})')

    files = MG5_FILES[channel]
    S_tot_pb, _ = sbe.kweight_sum_and_n(sbe.FRIENDS_DIR / files['sig'])
    B_tot_pb, _ = sbe.kweight_sum_and_n(sbe.FRIENDS_DIR / files['bkg'])
    r = sbe.RESCALE[channel]
    S = r * S_tot_pb * sbe.L * eff_sig
    B = r * B_tot_pb * sbe.L * eff_bkg
    sig    = float(S / np.sqrt(B)) if B > 0 else 0.0
    purity = float(S / (S + B)) if (S + B) > 0 else 0.0

    print(f'{net} {channel} [{objective}-max]: cut={cut:.6f}  Herwig grid point '
          f'eff_sig={r_hw["eff_sig"]:.6f} eff_bkg={r_hw["eff_bkg"]:.6f} -> Herwig at cut '
          f'eff_sig={eff_sig_hw:.6f} eff_bkg={eff_bkg_hw:.6f} (raw B={raw_B_hw})  |  '
          f'Pythia at same cut eff_sig={eff_sig:.6f} eff_bkg={eff_bkg:.6f}  '
          f'S={S:.1f}  B={B:.1f}  S/sqrt(B)={sig:.2f}')

    return dict(net=net, channel=channel, objective=objective, cut=cut,
                eff_sig=eff_sig, eff_bkg=eff_bkg,
                eff_sig_hw=eff_sig_hw, eff_bkg_hw=eff_bkg_hw,
                eff_sig_hw_grid=r_hw['eff_sig'], eff_bkg_hw_grid=r_hw['eff_bkg'],
                grid_to_cut_dist=float(np.sqrt(dist2[i_star])),
                floor_bound_hw=r_hw['floor_bound'],
                n_sig_hw=n_sig_hw, n_bkg_hw=n_bkg_hw,
                raw_S_hw=raw_S_hw, raw_B_hw=raw_B_hw,
                n_sig_py=n_sig_py, n_bkg_py=n_bkg_py,
                S=S, B=B, raw_S=n_sig, raw_B=n_bkg,
                significance=sig, purity=purity)


